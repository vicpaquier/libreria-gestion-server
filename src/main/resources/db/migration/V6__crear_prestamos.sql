CREATE TABLE prestamos (
    id_prestamo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    fecha_prestamo TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    estado VARCHAR NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_prestamos_estado
        CHECK (estado IN ('ACTIVO', 'DEVUELTO', 'ATRASADO', 'CANCELADO')),
    CONSTRAINT fk_prestamos_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE detalle_prestamo (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestamo BIGINT NOT NULL,
    id_libro BIGINT NOT NULL,
    fecha_devolucion TIMESTAMP WITH TIME ZONE,
    estado VARCHAR NOT NULL DEFAULT 'PRESTADO',
    CONSTRAINT ck_detalle_prestamo_estado
        CHECK (estado IN ('PRESTADO', 'DEVUELTO', 'PERDIDO')),
    CONSTRAINT fk_detalle_prestamo_prestamo FOREIGN KEY (id_prestamo)
        REFERENCES prestamos (id_prestamo) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_detalle_prestamo_libro FOREIGN KEY (id_libro)
        REFERENCES libros (id_libro) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX idx_prestamos_usuario ON prestamos (id_usuario);
CREATE INDEX idx_prestamos_estado ON prestamos (estado);
CREATE INDEX idx_detalle_prestamo_prestamo ON detalle_prestamo (id_prestamo);
CREATE INDEX idx_detalle_prestamo_libro ON detalle_prestamo (id_libro);
