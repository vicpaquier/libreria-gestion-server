CREATE TABLE libros (
    id_libro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR NOT NULL,
    isbn VARCHAR,
    anio_publicacion INTEGER,
    numero_paginas INTEGER,
    cantidad_total INTEGER NOT NULL,
    cantidad_disponible INTEGER NOT NULL,
    id_editorial BIGINT,
    CONSTRAINT uq_libros_isbn UNIQUE (isbn),
    CONSTRAINT ck_libros_cantidad_total CHECK (cantidad_total >= 0),
    CONSTRAINT ck_libros_cantidad_disponible CHECK (cantidad_disponible >= 0),
    CONSTRAINT ck_libros_disponible_total CHECK (cantidad_disponible <= cantidad_total),
    CONSTRAINT fk_libros_editorial FOREIGN KEY (id_editorial)
        REFERENCES editoriales (id_editorial) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE libro_autor (
    id_libro BIGINT NOT NULL,
    id_autor BIGINT NOT NULL,
    CONSTRAINT pk_libro_autor PRIMARY KEY (id_libro, id_autor),
    CONSTRAINT fk_libro_autor_libro FOREIGN KEY (id_libro)
        REFERENCES libros (id_libro) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_libro_autor_autor FOREIGN KEY (id_autor)
        REFERENCES autores (id_autor) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE libro_categoria (
    id_libro BIGINT NOT NULL,
    id_categoria BIGINT NOT NULL,
    CONSTRAINT pk_libro_categoria PRIMARY KEY (id_libro, id_categoria),
    CONSTRAINT fk_libro_categoria_libro FOREIGN KEY (id_libro)
        REFERENCES libros (id_libro) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_libro_categoria_categoria FOREIGN KEY (id_categoria)
        REFERENCES categorias (id_categoria) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE INDEX idx_libros_titulo ON libros (titulo);
CREATE INDEX idx_libros_isbn ON libros (isbn);
