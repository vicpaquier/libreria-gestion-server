CREATE TABLE reservas (
    id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_libro BIGINT NOT NULL,
    fecha_reserva TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion TIMESTAMP WITH TIME ZONE,
    estado VARCHAR NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT ck_reservas_estado
        CHECK (estado IN ('PENDIENTE', 'ATENDIDA', 'CANCELADA', 'EXPIRADA')),
    CONSTRAINT fk_reservas_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuarios (id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_reservas_libro FOREIGN KEY (id_libro)
        REFERENCES libros (id_libro) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_reservas_pendiente_usuario_libro
    ON reservas (id_usuario, id_libro) WHERE estado = 'PENDIENTE';
CREATE INDEX idx_reservas_usuario ON reservas (id_usuario);
CREATE INDEX idx_reservas_libro ON reservas (id_libro);
CREATE INDEX idx_reservas_estado ON reservas (estado);

CREATE TABLE multas (
    id_multa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestamo BIGINT NOT NULL,
    monto NUMERIC(19, 2) NOT NULL DEFAULT 0,
    motivo VARCHAR NOT NULL,
    fecha_multa TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT ck_multas_monto CHECK (monto >= 0),
    CONSTRAINT ck_multas_estado CHECK (estado IN ('PENDIENTE', 'PAGADA', 'CANCELADA')),
    CONSTRAINT fk_multas_prestamo FOREIGN KEY (id_prestamo)
        REFERENCES prestamos (id_prestamo) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX idx_multas_prestamo ON multas (id_prestamo);
CREATE INDEX idx_multas_estado ON multas (estado);
CREATE INDEX idx_multas_fecha ON multas (fecha_multa);
